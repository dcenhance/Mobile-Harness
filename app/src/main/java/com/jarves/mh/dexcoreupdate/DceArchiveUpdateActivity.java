  void showVerifiedIcon(java.io.File apk) {
    if (appIcon == null || apk == null) return;
    try {
      android.content.pm.PackageManager manager = getPackageManager();
      android.content.pm.PackageInfo archive = manager.getPackageArchiveInfo(apk.getAbsolutePath(), 0);
      if (archive == null || archive.applicationInfo == null) return;
      archive.applicationInfo.sourceDir = apk.getAbsolutePath();
      archive.applicationInfo.publicSourceDir = apk.getAbsolutePath();
      android.graphics.drawable.Drawable icon = launcherShapedIcon(manager.getApplicationIcon(archive.applicationInfo));
      if (icon != null) appIcon.setImageDrawable(icon);
    } catch (Exception unavailable) { /* the installed icon stays */ }
  }
  // The launcher draws the app icon inside the device's own icon shape. A legacy
  // (non-adaptive) icon handed straight to the notice is a hard square - the artwork the
  // user sees nowhere else on the device, which is what made the identity line look wrong.
  // The notice rounds the same artwork instead of replacing it; an adaptive icon already
  // carries its own mask, so it is passed through untouched.
  private android.graphics.drawable.Drawable launcherShapedIcon(android.graphics.drawable.Drawable icon) {
    if (icon == null) return null;
    if (Build.VERSION.SDK_INT >= 26 && icon instanceof android.graphics.drawable.AdaptiveIconDrawable) return icon;
    try {
      int side = Math.max(1, getResources().getDimensionPixelSize(android.R.dimen.app_icon_size));
      android.graphics.Bitmap bitmap = android.graphics.Bitmap.createBitmap(side, side, android.graphics.Bitmap.Config.ARGB_8888);
      android.graphics.Canvas canvas = new android.graphics.Canvas(bitmap);
      android.graphics.Path shape = new android.graphics.Path();
      float radius = side * .224f;
      shape.addRoundRect(new android.graphics.RectF(0f, 0f, side, side), radius, radius, android.graphics.Path.Direction.CW);
      canvas.clipPath(shape);
      icon.setBounds(0, 0, side, side);
      icon.draw(canvas);
      return new android.graphics.drawable.BitmapDrawable(getResources(), bitmap);
    } catch (Exception unavailable) { return icon; }
  }
