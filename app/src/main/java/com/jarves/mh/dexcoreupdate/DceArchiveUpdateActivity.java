  // Returns true only when the postponement was recorded and the notice closed.
  private boolean postpone() {
    if (transferBusy) return false;
    if (appUpdate) {
      if (!DceArchiveUpdates.canPostpone(this, targetVersion)) return false;
      DceArchiveUpdates.recordPostponement(this, targetVersion);
    } else if (catalogRequired || !dataUpdate) {
      return false;
    }
    // A postponed notice also settles any optional content it was announcing, so
    // the same revision does not come back with every foreground check.
    if (dataUpdate && !catalogRequired) DceArchiveUpdates.acknowledgeCatalog(this, update);
    if (dialog != null && dialog.isShowing()) dialog.dismiss();
    else finish();
    return true;
  }

