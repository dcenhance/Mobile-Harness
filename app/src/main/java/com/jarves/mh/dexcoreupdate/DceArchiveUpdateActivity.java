  private GradientDrawable card(int color, int radius) { GradientDrawable shape = round(color, radius); shape.setStroke(dp(1), Color.argb(46, Color.red(accentInk), Color.green(accentInk), Color.blue(accentInk))); return shape; }
  private int dp(int value) { return (int) (value * getResources().getDisplayMetrics().density + .5f); }
  // One width rule for the whole notice: the card, the pack list it measures against and
  // the window it is laid out in must agree, or the list is measured against a width the
  // card does not have. The cap keeps it a card on a tablet instead of a full-width sheet.
  private int noticeWidth() { return Math.min(dp(560), (int) (getResources().getDisplayMetrics().widthPixels * .92f)); }
