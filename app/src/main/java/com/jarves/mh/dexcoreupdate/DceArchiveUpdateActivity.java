  private boolean isTelevision() { return (getResources().getConfiguration().uiMode & android.content.res.Configuration.UI_MODE_TYPE_MASK) == android.content.res.Configuration.UI_MODE_TYPE_TELEVISION; }
  private void highlightAction(TextView view, boolean primary, boolean focused) {
    int fill = primary ? accent : focused ? blend(surface, accentInk, .16d) : Color.TRANSPARENT;
    GradientDrawable shape = round(fill, 15);
    if (focused) shape.setStroke(dp(3), readableOn(textPrimary, fill == Color.TRANSPARENT ? surface : fill, 3d));
    else if (!primary) shape.setStroke(dp(1), Color.argb(168, Color.red(accentInk), Color.green(accentInk), Color.blue(accentInk)));
    view.setBackground(shape);
    view.animate().scaleX(focused ? 1.035f : 1f).scaleY(focused ? 1.035f : 1f).setDuration(130).start();
  }
  @SuppressLint("ClickableViewAccessibility")
  private void tactile(TextView view, boolean primary) {
    view.setFocusable(true); view.setClickable(true);
    if (isTelevision()) {
      view.setOnFocusChangeListener((target, focused) -> highlightAction(view, primary, focused));
      view.setOnHoverListener((target, event) -> {
        if (event.getActionMasked() == android.view.MotionEvent.ACTION_HOVER_ENTER && target.isEnabled()) target.requestFocus();
        return false;
      });
    }
    view.setOnTouchListener((target, event) -> {
      if (!target.isEnabled()) return false;
      boolean pressed = event.getActionMasked() == android.view.MotionEvent.ACTION_DOWN;
      if (!isTelevision()) target.animate().scaleX(pressed ? .98f : 1f).scaleY(pressed ? .98f : 1f).setDuration(120).start();
      return false;
    });
  }
